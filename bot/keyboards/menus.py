"""كل قوائم Reply — مطابقة للملف القديم 100%"""
from pyrogram.types import ReplyKeyboardMarkup, KeyboardButton
from bot.keyboards.constants import t


def _kb(rows: list) -> ReplyKeyboardMarkup:
    """helper: يحول list of lists → ReplyKeyboardMarkup"""
    return ReplyKeyboardMarkup(
        [[KeyboardButton(text=btn) for btn in row] for row in rows],
        resize_keyboard=True
    )


